"""Explicit screenshot maintenance; both commands default to dry-run.

GC requires a quiet database and briefly blocks application writes per deletion.
Only references persisted in this database are roots: external dataset manifests,
other databases, and clients holding unpublished URIs must be quiesced separately.
Screenshot keys must remain immutable (as generated by artifacts.put_png).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from collections import Counter
from contextlib import closing
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Iterator

from psycopg import sql
from psycopg.types.json import Jsonb

from alvarezgui import artifacts
from alvarezgui.config import Settings
from alvarezgui.db import connect

TERMINAL = ("SUCCEEDED", "FAILED", "CANCELED")
# Scan every column, including JSON, registry URIs, dataset sources and logs.
# Keep in sync with migrations when adding a table which can retain a URI.
REFERENCE_TABLES = (
    "artifacts", "datasets", "episodes", "evaluations", "model_versions", "nodes",
    "sandbox_leases", "steps", "tasks", "training_metrics", "training_runs",
)


def _strings(value: Any) -> Iterator[str]:
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for key, child in value.items():
            yield key
            yield from _strings(child)
    elif isinstance(value, list):
        for child in value:
            yield from _strings(child)


def _image_paths(value: Any, path: tuple[str, ...] = ()) -> Iterator[tuple[tuple[str, ...], str]]:
    if isinstance(value, dict):
        for key, child in value.items():
            if key == "image_uri" and isinstance(child, str) and child.startswith("file:"):
                yield path + (key,), child
            else:
                yield from _image_paths(child, path + (key,))
    elif isinstance(value, list):
        for index, child in enumerate(value):
            yield from _image_paths(child, path + (str(index),))


def migrate(settings: Settings, *, apply: bool = False, roots: tuple[Path, ...] = ()) -> dict[str, int]:
    """Migrate terminal episodes' image_uri JSON leaves, keeping every local file.

    Extra roots explicitly authorize reading referenced historical evidence outside
    data_dir/runs and microvm_state_dir/runs. Counts are per reference, except rows,
    uploads and errors. Each row commits independently; failed CAS leaves it alone.
    """
    allowed = tuple(root.resolve() for root in (
        settings.data_dir / "runs", settings.microvm_state_dir / "runs", *roots,
    ))
    counts = Counter({key: 0 for key in (
        "rows", "references", "eligible", "missing", "unmanaged", "uploaded",
        "updated", "conflicts", "errors",
    )})
    uploaded: dict[tuple[str, bytes], str] = {}
    with connect(settings) as connection:
        connection.autocommit = True
        for table, column, keys in (
            ("steps", "observation", ("episode_id", "step_id")),
            ("episodes", "result", ("episode_id",)),
        ):
            # ponytail: snapshot one table in memory; keyset batches if history outgrows RAM.
            rows = connection.execute(sql.SQL(
                "SELECT r.* FROM {} r JOIN episodes e ON r.episode_id = e.episode_id "
                "JOIN tasks t ON e.task_id = t.task_id "
                "WHERE e.status = ANY(%s) AND t.status = ANY(%s)"
            ).format(sql.Identifier(table)), (list(TERMINAL), list(TERMINAL))).fetchall()
            for row in rows:
                paths = list(_image_paths(row[column]))
                if not paths:
                    continue
                counts["rows"] += 1
                changes = 0
                try:
                    with connection.transaction():
                        for path, old_uri in paths:
                            counts["references"] += 1
                            local = artifacts.local_file(old_uri)
                            if local is None or not local.is_absolute():
                                counts["unmanaged"] += 1
                                continue
                            local = local.resolve()
                            if not any(local.is_relative_to(root) for root in allowed):
                                counts["unmanaged"] += 1
                                continue
                            if not local.is_file():
                                counts["missing"] += 1
                                continue
                            with local.open("rb") as source:
                                payload = source.read(artifacts.MAX_ARTIFACT_BYTES + 1)
                            if len(payload) > artifacts.MAX_ARTIFACT_BYTES:
                                raise ValueError("screenshot exceeds storage limit")
                            counts["eligible"] += 1
                            if not apply:
                                continue
                            digest = hashlib.sha256(payload).digest()
                            upload_key = (old_uri, digest)
                            if upload_key not in uploaded:
                                new_uri = artifacts.put_png(settings, payload, sandbox_id="migration")
                                counts["uploaded"] += 1
                                if hashlib.sha256(artifacts.get(settings, new_uri)).digest() != digest:
                                    raise ValueError("uploaded screenshot digest mismatch")
                                uploaded[upload_key] = new_uri
                            where = sql.SQL(" AND ").join(
                                sql.SQL("{} = %s").format(sql.Identifier(key)) for key in keys
                            )
                            changed = connection.execute(sql.SQL(
                                "UPDATE {} SET {} = jsonb_set({}, %s, %s, false) "
                                "WHERE {} AND {} #>> %s = %s"
                            ).format(sql.Identifier(table), sql.Identifier(column), sql.Identifier(column),
                                     where, sql.Identifier(column)),
                                (list(path), Jsonb(uploaded[upload_key]), *(row[key] for key in keys),
                                 list(path), old_uri),
                            ).rowcount
                            changes += changed
                            counts["conflicts"] += 1 - changed
                    counts["updated"] += changes
                except Exception:
                    # Uploaded but uncommitted objects are harmless GC candidates after grace.
                    counts["errors"] += 1
    return dict(counts)


def _active(connection: Any) -> bool:
    for table in ("tasks", "episodes", "training_runs"):
        if connection.execute(sql.SQL(
            "SELECT 1 FROM {} WHERE status <> ALL(%s) LIMIT 1"
        ).format(sql.Identifier(table)), (list(TERMINAL),)).fetchone():
            return True
    return connection.execute("SELECT 1 FROM sandbox_leases LIMIT 1").fetchone() is not None


def _references(connection: Any, bucket: str) -> set[str]:
    prefix = f"s3://{bucket}"
    references: set[str] = set()
    for table in REFERENCE_TABLES:
        for row in connection.execute(sql.SQL("SELECT to_jsonb(r) AS document FROM {} r").format(
            sql.Identifier(table),
        )):
            references.update(text for text in _strings(row["document"]) if prefix in text)
    return references


def _referenced(uri: str, references: set[str]) -> bool:
    # Embedded URIs and registered directory prefixes deliberately over-retain.
    return any(uri in text or (text.startswith("s3://") and uri.startswith(text.rstrip("/") + "/"))
               for text in references)


def _old(metadata: dict[str, Any], cutoff: datetime) -> bool:
    modified = metadata.get("LastModified")
    return isinstance(modified, datetime) and modified.tzinfo is not None and modified < cutoff


def gc(settings: Settings, *, apply: bool = False, grace_days: float = 30) -> dict[str, int]:
    """Collect old, unreferenced screenshots in the configured bucket only.

    Each delete rechecks references and active work under SHARE table locks, so
    concurrent database writers cannot introduce a reference between check/delete.
    No external writer may overwrite/reuse screenshot keys while GC runs.
    """
    if not math.isfinite(grace_days) or grace_days <= 0:
        raise ValueError("grace_days must be finite and positive")
    cutoff = datetime.now(timezone.utc) - timedelta(days=grace_days)
    counts = Counter({key: 0 for key in (
        "scanned", "recent", "referenced", "candidates", "deleted", "changed", "active", "errors",
    )})
    with connect(settings) as connection, closing(artifacts.client(settings)) as storage:
        connection.autocommit = True
        with connection.transaction():
            connection.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY")
            if _active(connection):
                counts["active"] += 1
                return dict(counts)
            references = _references(connection, settings.minio_bucket)
        for page in storage.get_paginator("list_objects_v2").paginate(
            Bucket=settings.minio_bucket, Prefix="screenshots/",
        ):
            for obj in page.get("Contents", []):
                key = obj["Key"]
                if not key.startswith("screenshots/"):
                    continue
                counts["scanned"] += 1
                if not _old(obj, cutoff):
                    counts["recent"] += 1
                    continue
                uri = f"s3://{settings.minio_bucket}/{key}"
                if _referenced(uri, references):
                    counts["referenced"] += 1
                    continue
                counts["candidates"] += 1
                if not apply:
                    continue
                try:
                    with connection.transaction():
                        # ponytail: O(objects * database size), with global write locks;
                        # add a reference index and coordinated writers if GC becomes costly.
                        connection.execute(sql.SQL("LOCK TABLE {} IN SHARE MODE").format(
                            sql.SQL(", ").join(map(sql.Identifier, REFERENCE_TABLES)),
                        ))
                        if _active(connection):
                            counts["active"] += 1
                            return dict(counts)
                        if _referenced(uri, _references(connection, settings.minio_bucket)):
                            counts["referenced"] += 1
                            continue
                        current = storage.head_object(Bucket=settings.minio_bucket, Key=key)
                        if (not _old(current, cutoff) or current["LastModified"] != obj["LastModified"]
                                or current.get("ETag") != obj.get("ETag")):
                            counts["changed"] += 1
                            continue
                        storage.delete_object(Bucket=settings.minio_bucket, Key=key)
                        counts["deleted"] += 1
                except Exception:
                    counts["errors"] += 1
    return dict(counts)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    for name in ("migrate", "gc"):
        command = commands.add_parser(name)
        mode = command.add_mutually_exclusive_group()
        mode.add_argument("--apply", action="store_true", help="perform writes (default: dry-run)")
        mode.add_argument("--dry-run", action="store_true", help="report only; never write")
        if name == "migrate":
            command.add_argument("--root", type=Path, action="append", default=[],
                                 help="additional allowed evidence directory; repeatable")
        else:
            command.add_argument("--grace-days", type=float)
    args = parser.parse_args(argv)
    settings = Settings()
    counts = (migrate(settings, apply=args.apply, roots=tuple(args.root)) if args.command == "migrate"
              else gc(settings, apply=args.apply, grace_days=(
                  args.grace_days if args.grace_days is not None else settings.artifact_retention_days)))
    print(json.dumps({"command": args.command, "apply": args.apply, **counts}, sort_keys=True))
    return 1 if counts["errors"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
